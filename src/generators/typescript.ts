// ─── built-in extract command injection ─────────────────────────

function generateBuiltinExtractCommand(
  ctx: NormalizedContext,
  lines: string[],
): void {
  const executable = ctx.command_sets[0].executable;
  const allFullIds = ctx.command_sets.flatMap((cs) =>
    cs.commands.map((c) => c.full_id),
  );

  lines.push("");
  lines.push("  // Built-in extract command (auto-injected by cli-contracts)");
  lines.push("  program");
  lines.push('    .command("extract")');
  lines.push('    .description("Extract contract specification for this CLI tool.")');
  lines.push('    .argument("[commands...]", "Command IDs to extract. Use dot notation.")');
  lines.push('    .option("-a, --all", "Extract all commands.", false)');
  lines.push('    .option("--include-meta", "Include extraction metadata.", true)');
  lines.push('    .option("-F, --format <format>", "Output format (yaml or json).", "yaml")');
  lines.push("    .action(async (commands: string[], opts: { all?: boolean; includeMeta?: boolean; format?: string }) => {");
  lines.push("      if (commands.length === 0 && !opts.all) {");
  lines.push('        process.stderr.write(JSON.stringify({ code: "INVALID_ARGS", message: "Specify command IDs or use --all" }) + "\\n");');
  lines.push("        process.exit(2);");
  lines.push("      }");
  lines.push("");
  lines.push("      const format = opts.format || \"yaml\";");
  lines.push("      const doc = JSON.parse(CONTRACT_JSON_STR);");
  lines.push("      const cmdIds = opts.all ? [] : commands;");
  lines.push("");
  lines.push("      if (cmdIds.length === 0) {");
  lines.push("        // --all: output full contract");
  lines.push("        if (format === \"json\") {");
  lines.push("          const out: Record<string, unknown> = {};");
  lines.push("          if (opts.includeMeta) {");
  lines.push(`            out._meta = {`);
  lines.push(`              source: "embedded",`);
  lines.push(`              type: "cli-contracts/extract",`);
  lines.push(`              extractedAt: new Date().toISOString(),`);
  lines.push(`              specVersion: doc.cli_contracts ?? "0.1.0",`);
  lines.push(`              commands: ${JSON.stringify(allFullIds)},`);
  lines.push(`            };`);
  lines.push("          }");
  lines.push("          Object.assign(out, doc);");
  lines.push('          process.stdout.write(JSON.stringify(out, null, 2) + "\\n");');
  lines.push("        } else {");
  lines.push("          // YAML output");
  lines.push("          const yamlLines: string[] = [];");
  lines.push(`          yamlLines.push("# ${executable} extract");`);
  lines.push(`          yamlLines.push("# source: embedded");`);
  lines.push(`          yamlLines.push("# type: cli-contracts/command-extract");`);
  lines.push("          if (opts.includeMeta) {");
  lines.push('            yamlLines.push("---");');
  lines.push(`            yamlLines.push("source: embedded");`);
  lines.push(`            yamlLines.push("type: cli-contracts/command-extract");`);
  lines.push(`            yamlLines.push("extractedAt: " + new Date().toISOString());`);
  lines.push(`            yamlLines.push("spec_version: " + (doc.cli_contracts ?? "0.1.0"));`);
  lines.push(`            yamlLines.push("commands:");`);
  lines.push(`            for (const id of ${JSON.stringify(allFullIds)}) {`);
  lines.push(`              yamlLines.push("  - " + id);`);
  lines.push("            }");
  lines.push("          }");
  lines.push('          yamlLines.push("---");');
  lines.push("          yamlLines.push(CONTRACT_YAML);");
  lines.push('          process.stdout.write(yamlLines.join("\\n") + "\\n");');
  lines.push("        }");
  lines.push("      } else {");
  lines.push("        // Filter specific commands");
  lines.push("        const filtered: Record<string, unknown> = {");
  lines.push("          cli_contracts: doc.cli_contracts,");
  lines.push("          info: doc.info,");
  lines.push("          command_sets: {},");
  lines.push("        };");
  lines.push("        const fcs = filtered.command_sets as Record<string, Record<string, unknown>>;");
  lines.push("        for (const [setId, cs] of Object.entries(doc.command_sets ?? {})) {");
  lines.push("          const cmds = (cs as Record<string, unknown>).commands as Record<string, unknown> | undefined;");
  lines.push("          if (!cmds) continue;");
  lines.push("          const matched: Record<string, unknown> = {};");
  lines.push("          for (const [cmdId, cmdDef] of Object.entries(cmds)) {");
  lines.push("            const fullId = setId + \".\" + cmdId;");
  lines.push("            if (cmdIds.some((id) => id === cmdId || id === fullId || cmdId.startsWith(id + \".\"))) {");
  lines.push("              matched[cmdId] = cmdDef;");
  lines.push("            }");
  lines.push("          }");
  lines.push("          if (Object.keys(matched).length > 0) {");
  lines.push("            const setCopy = { ...(cs as Record<string, unknown>) };");
  lines.push("            setCopy.commands = matched;");
  lines.push("            fcs[setId] = setCopy;");
  lines.push("          }");
  lines.push("        }");
  lines.push("        if (doc.components) filtered.components = doc.components;");
  lines.push('        process.stdout.write(JSON.stringify(filtered, null, 2) + "\\n");');
  lines.push("      }");
  lines.push("      process.exit(0);");
  lines.push("    });");
}
